/// 率（打率・出塁率・長打率・OPS・勝率など）の表示整形。
///
/// 野球の慣習では、1 未満の率は先頭の「0」を落として表示する
/// （例: 0.321 → .321、0.500 → .500）。
/// OPS・長打率は 1 以上になりうるので、その場合は先頭を残す（例: 1.234）。
String formatRate3(double v) {
  final s = v.toStringAsFixed(3);
  // 「0.321」→「.321」。「1.234」やマイナスはそのまま。
  return s.startsWith('0.') ? s.substring(1) : s;
}
